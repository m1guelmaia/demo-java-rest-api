package m1guelmaia.math;

public class SimpleMath {

    public Double sum(Double first, Double second) {
        return first + second;
    }

    public Double subtraction(Double first, Double second) {
        return first - second;
    }

    public Double multiplication(Double first, Double second) {
        return first * second;
    }

    public Double division(Double first, Double second) {
        return first / second;
    }

    public Double average(Double first, Double second) {
        return (first + second) / 2;
    }

    public Double squareRoot(Double first) {
        return Math.sqrt(first);
    }
}
